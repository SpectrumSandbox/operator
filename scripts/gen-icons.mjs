import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = process.argv[2];
if (!dir) throw new Error('pass the lucide icons directory');

const NAMES = `plane plane-takeoff plane-landing radar map map-pin layers cloud-rain wind cloud eye eye-off sun moon thermometer gauge
battery battery-charging battery-low battery-warning battery-full zap cpu wrench triangle-alert octagon-alert circle-alert check
circle-check x circle-x clock calendar calendar-days chart-gantt chart-column chart-line chart-pie activity radio radio-tower
satellite signal wifi wifi-off shield shield-alert shield-check users user user-check package truck ship building warehouse
crosshair navigation navigation-2 compass route target scan scan-line camera aperture flame siren life-buoy sprout leaf trees
mountain waves-horizontal waves anchor search funnel sliders-horizontal settings database server cloud-upload download file-text
file-check printer play pause square rotate-ccw refresh-cw sparkles bot brain chevron-right chevron-left chevron-down chevron-up
arrow-right arrow-up-right external-link plus minus ellipsis list grid-3x3 lock lock-open info bell house timer hourglass power
link unlink drone cable box boxes clipboard-check clipboard-list cog circle-dot dot locate locate-fixed move-right user-cog
file-down sheet hard-drive helicopter fuel weight ruler scale cloud-lightning cloud-fog sunrise sunset split merge git-branch
shuffle repeat flag megaphone ban octagon-x tower-control history-icon rotate-cw arrow-down-right arrow-up arrow-down maximize-2
minimize-2 layout-grid gauge-circle trending-up trending-down circle-pause circle-play crosshair`
  .split(/\s+/)
  .filter(Boolean);

const toPascal = (s) => s.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());
const entries = [];
const seen = new Set();
for (const name of NAMES) {
  if (seen.has(name)) continue;
  seen.add(name);
  const file = path.join(dir, `${name}.svg`);
  if (!fs.existsSync(file)) {
    console.warn('skip (not in lucide):', name);
    continue;
  }
  const svg = fs.readFileSync(file, 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
  const nodes = [];
  for (const m of inner.matchAll(/<(\w+)([^>]*?)\/?>/g)) {
    const attrs = {};
    for (const a of m[2].matchAll(/([\w-]+)="([^"]*)"/g)) attrs[a[1]] = a[2];
    nodes.push([m[1], attrs]);
  }
  entries.push([name, nodes]);
}

const body = `// AUTO-GENERATED by scripts/gen-icons.mjs from Lucide (ISC License, (c) Lucide Icons and Contributors).
// Do not edit by hand.
import { createElement, type CSSProperties } from 'react';

type IconNode = [string, Record<string, string>][];

const ICONS = {
${entries.map(([n, nodes]) => `  '${n}': ${JSON.stringify(nodes)},`).join('\n')}
} satisfies Record<string, IconNode>;

export type IconName = keyof typeof ICONS;

export interface IconProps {
  name: IconName;
  size?: number;
  strokeWidth?: number;
  className?: string;
  style?: CSSProperties;
  title?: string;
}

/** Lucide icon renderer. */
export function Icon({ name, size = 14, strokeWidth = 1.75, className, style, title }: IconProps) {
  const nodes = ICONS[name] as IconNode;
  return createElement(
    'svg',
    {
      xmlns: 'http://www.w3.org/2000/svg',
      width: size,
      height: size,
      viewBox: '0 0 24 24',
      fill: 'none',
      stroke: 'currentColor',
      strokeWidth,
      strokeLinecap: 'round',
      strokeLinejoin: 'round',
      className: 'shrink-0 ' + (className ?? ''),
      style,
      'aria-hidden': title ? undefined : true,
      role: title ? 'img' : undefined,
    },
    title ? createElement('title', { key: 't' }, title) : null,
    ...nodes.map(([tag, attrs], i) => createElement(tag, { key: i, ...attrs })),
  );
}

/** Raw SVG markup (for Leaflet divIcons). */
export function iconSvg(name: IconName, size = 14, color = 'currentColor', strokeWidth = 2): string {
  const nodes = ICONS[name] as IconNode;
  const inner = nodes
    .map(([tag, attrs]) => '<' + tag + ' ' + Object.entries(attrs).map(([k, v]) => k + '="' + v + '"').join(' ') + '/>')
    .join('');
  return '<svg xmlns="http://www.w3.org/2000/svg" width="' + size + '" height="' + size + '" viewBox="0 0 24 24" fill="none" stroke="' + color + '" stroke-width="' + strokeWidth + '" stroke-linecap="round" stroke-linejoin="round">' + inner + '</svg>';
}
`;

fs.writeFileSync(path.join(root, 'src/ui/icons.tsx'), body);
console.log(`wrote ${entries.length} icons`);
